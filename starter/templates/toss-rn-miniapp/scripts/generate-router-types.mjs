import fs from 'node:fs';
import path from 'node:path';

const PROJECT_ROOT = process.cwd();
const PAGES_ROOT = path.join(PROJECT_ROOT, 'pages');
const OUTPUT_PATH = path.join(PROJECT_ROOT, 'src', 'router.gen.ts');

function isPageFile(fileName) {
  return /\.[cm]?[tj]sx?$/.test(fileName) && !fileName.startsWith('_');
}

function walkPages(currentDir) {
  const entries = fs.readdirSync(currentDir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const absolutePath = path.join(currentDir, entry.name);

    if (entry.isDirectory()) {
      files.push(...walkPages(absolutePath));
      continue;
    }

    if (entry.isFile() && isPageFile(entry.name)) {
      files.push(absolutePath);
    }
  }

  return files;
}

function toRoutePath(pageFilePath) {
  const relativePath = path.relative(PAGES_ROOT, pageFilePath).replace(/\\/g, '/');
  const withoutExtension = relativePath.replace(/\.[^.]+$/, '');
  const normalized = withoutExtension === 'index'
    ? '/'
    : `/${withoutExtension.replace(/\/index$/, '').replace(/\/+/g, '/')}`;

  return normalized === '//' ? '/' : normalized;
}

function toImportPath(pageFilePath) {
  const relativePath = path.relative(path.dirname(OUTPUT_PATH), pageFilePath).replace(/\\/g, '/');
  return relativePath.replace(/\.[^.]+$/, '').replace(/^(?!\.)/, './');
}

function toAlias(routePath) {
  if (routePath === '/') {
    return 'Index';
  }

  return routePath
    .replace(/^\//, '')
    .split('/')
    .map((segment) => segment.replace(/[^a-zA-Z0-9]+/g, ' '))
    .map((segment) => segment.trim())
    .filter(Boolean)
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join('');
}

if (!fs.existsSync(PAGES_ROOT)) {
  throw new Error(`pages directory not found: ${PAGES_ROOT}`);
}

const pageFiles = walkPages(PAGES_ROOT)
  .map((pageFilePath) => ({
    pageFilePath,
    routePath: toRoutePath(pageFilePath),
    importPath: toImportPath(pageFilePath),
    alias: toAlias(toRoutePath(pageFilePath)),
  }))
  .sort((a, b) => a.routePath.localeCompare(b.routePath));

const importLines = pageFiles.map(
  ({ alias, importPath }) => `import { Route as _${alias}Route } from '${importPath}';`,
);

const registerScreenInputLines = pageFiles.map(
  ({ alias, routePath }) => `    '${routePath}': (typeof _${alias}Route)['_inputType'];`,
);

const registerScreenLines = pageFiles.map(
  ({ alias, routePath }) => `    '${routePath}': (typeof _${alias}Route)['_outputType'];`,
);

const fileContents = `/* eslint-disable */
// This file is auto-generated by the Toss RN starter. Run \`pnpm router:types\` after changing pages.
${importLines.join('\n')}

declare module '@granite-js/react-native' {
  interface RegisterScreenInput {
${registerScreenInputLines.join('\n')}
  }

  interface RegisterScreen {
${registerScreenLines.join('\n')}
  }
}
`;

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
fs.writeFileSync(OUTPUT_PATH, fileContents);

console.log(`generated router types: ${path.relative(PROJECT_ROOT, OUTPUT_PATH)}`);
