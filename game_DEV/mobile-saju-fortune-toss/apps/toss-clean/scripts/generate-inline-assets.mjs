function dailyAssetConfigs(groupName, keys, pathSegments) {
  return keys.map((key) => ({
    exportName: `DAILY_${groupName}_${key.toUpperCase()}_DATA_URI`,
    filePath: resolve(appDir, ...pathSegments, `${key}.png`),
    mimeType: 'image/png',
  }));
}

